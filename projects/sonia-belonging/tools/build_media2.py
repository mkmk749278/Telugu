#!/usr/bin/env python3
"""v3 media: the Cowork photos (photos2) and the Pixabay stock clips, copied into public/media and listed in
src/media2.ts (P = photos, S = stock clips) with credit lines. Run after pulling assets."""
import csv, json, shutil, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
A = ROOT / 'assets/sonia-belonging'
PUB = ROOT / 'projects/sonia-belonging/remotion/public/media'
(PUB / 'p2').mkdir(parents=True, exist_ok=True); (PUB / 'stock').mkdir(parents=True, exist_ok=True)
items = json.load(open(ROOT / 'projects/sonia-belonging/tools/photos2.json'))
extra = {'babri': ('Babri Masjid.jpg', 'Public domain', 'Samuel Bourne'), }
lines = ['// Generated by tools/build_media2.py. Do not edit by hand.', 'export const P = {']
for k, t, lic, art in items:
    src = next((p for p in (A / 'photos2').glob(k + '.*')), None)
    if not src: continue
    dst = PUB / 'p2' / f'{k}.jpg'
    subprocess.run(['convert', str(src) + '[0]', '-auto-orient', '-resize', '3840x3840>', '-quality', '90', str(dst)], check=True)
    title = t.rsplit('.', 1)[0][:60]
    lines.append(f'\t{k}: {{file: "p2/{k}.jpg", credit: {json.dumps(f"Photo: {art} · {lic} · Wikimedia Commons", ensure_ascii=False)}}},')
lines += ['} as const;', '', 'export const S = {']
for row in csv.DictReader(open(A / 'stock/stock.csv')):
    shutil.copy(A / 'stock' / f"{row['key']}.mp4", PUB / 'stock' / f"{row['key']}.mp4")
    sec = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(PUB / 'stock' / f"{row['key']}.mp4")], capture_output=True, text=True).stdout)
    lines.append(f"\t{row['key']}: {{file: \"stock/{row['key']}.mp4\", sec: {sec:.2f}, credit: {json.dumps('Stock footage · ' + row['author'] + ' · Pixabay', ensure_ascii=False)}}},")
lines += ['} as const;', '']
(ROOT / 'projects/sonia-belonging/remotion/src/media2.ts').write_text('\n'.join(lines))
print('ok', len(lines))

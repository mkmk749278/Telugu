#!/usr/bin/env python3
"""Build remotion/src/media.ts (shot key -> file + credit) from the Commons manifest, and copy the files into
remotion/public/media. A missing photo is an error unless --allow-missing (then it points at a stand-in, listed)."""
import json, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PHOTOS = ROOT / 'assets/sonia-belonging/photos'
PUB = ROOT / 'projects/sonia-belonging/remotion/public/media'
KEYS = {  # key: Commons file title (exact)
    'sonia2007': 'Gandhisonia05052007.jpg',
    'clinton2000': 'President Clinton with Sonia Gandhi and Manmohan Singh.jpg',
    'sonia2006': 'Sonia Gandhi - India Economic Summit 2006.jpg',
    'birthplace': 'Sonia Gandhi birthplace.JPG',
    'sonia2013': 'Sonia Gandhi in 2013.jpg',
    'doon1997': 'Sonia Gandhi at The Doon School, 20 October 1997.png',
    'indira1966': 'Indira Gandhi 1966.jpg',
    'indira1977': 'Premier Indira Gandhi (Congrespartij), Bestanddeelnr 929-0811.jpg',
    'indira1983': 'Indira-Gandhi-in-Finland-1983.jpg',
    'family1949': 'Indira Gandhi, Jawaharlal Nehru, Rajiv Gandhi and Sanjay Gandhi.jpg',
    'memorial1': 'Indira Gandhi Memorial Delhi-India4451.JPG',
    'memorial2': 'Indira Gandhi Memorial Delhi-India4462.JPG',
    'rajiv1985': 'Rajiv Gandhi-cropped.jpg',
    'rajiv1987': 'Rajiv Gandhi (1987).jpg',
    'rajivThatcher': 'Rajiv Gandhi and Margaret Thatcher (1985).jpg',
    'sriperumbudur': 'Rajiv gandhi samadhi sriperumbudur.jpg',
    'kingsParade1980': "King's Parade, Cambridge - geograph.org.uk - 4830013.jpg",
    'senateHouse': 'Cambridge-University-Senate-House.jpg',
    'parliament': 'Sansad Bhavan, Delhi, BNK.jpg',
    'vizag': 'Ramakrishna Beach road in Visakhapatnam (June 2019).jpg',
    'hydBookstore': 'LandmarkBookStore BanjaraHills Hyderabad.jpg',
    'requiem': 'K626 Requiem Mozart.jpg',
    'safdarjungLane': 'Safdarjung lane delhi.jpg',
    'pvrao': 'P. V. Narasimha Rao.JPG',
    'natwar': 'K. Natwar Singh.jpg',
    'modi': 'Narendra Damodardas Modi.jpg',
    'manmohan': 'Official Portrait of the Prime Minister Dr. Manmohan Singh.jpg',
}
man = json.loads((PHOTOS / 'manifest.json').read_text())
by_title = {m['title'][5:]: m for m in man}
PUB.mkdir(parents=True, exist_ok=True)
lines, missing = [], []
stand_in = next(iter(by_title.values()))
for k, t in KEYS.items():
    m = by_title.get(t)
    if not m:
        missing.append(k)
        m = stand_in
    shutil.copy(PHOTOS / m['file'], PUB / m['file'])
    author = m['author'].split('\n')[0][:60]
    credit = f"{t.rsplit('.', 1)[0][:70]} · {author} · {m['licence']} · Wikimedia Commons"
    lines.append(f"\t{k}: {{file: {json.dumps(m['file'])}, credit: {json.dumps(credit, ensure_ascii=False)}}},")
(PUB / 'book').mkdir(exist_ok=True)
shutil.copy(ROOT / 'assets/sonia-belonging/book/cover.jpg', PUB / 'book/cover.jpg')
out = ROOT / 'projects/sonia-belonging/remotion/src/media.ts'
out.write_text('// Generated by tools/build_media.py from the Commons manifest. Do not edit by hand.\nexport const M = {\n' + '\n'.join(lines) + '\n} as const;\n')
print('missing:', missing)
if missing and '--allow-missing' not in sys.argv:
    sys.exit(1)
